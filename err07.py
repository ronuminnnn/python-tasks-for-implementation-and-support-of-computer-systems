# Err7. Читать ввод, пока не будет введено целое число. 
# Некорректный ввод не роняет программу и не считается: печатается «Это не число. Попробуй ещё:», чтение повторяется. 
# Вывести полученное число.
while True:
    try:
        number = int(input())
        break
    except ValueError:
        print("Это не число. Попробуй еще:")
print(number)