# Err9. Прочитать возраст. Если число отрицательное или больше 120, поднять ValueError с текстом «Возраст вне допустимого диапазона» 
# и поймать его же: в except вывести «Отклонено:» и текст ошибки. Корректный возраст вывести как «Принято:» и число.
try:
    age = int(input())
    if age < 0 or age > 120:
        raise ValueError("Возраст вне допустимого диапазона")
except ValueError as e:
    print("Отклонено:", e)
else:
    print("Принято:", age)